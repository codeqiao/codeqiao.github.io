CREATE TABLE IF NOT EXISTS likes (
  path TEXT NOT NULL,
  visitor TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (path, visitor)
) WITHOUT ROWID;

CREATE VIEW IF NOT EXISTS like_totals AS
SELECT path, COUNT(*) AS likes FROM likes GROUP BY path;


CREATE TABLE IF NOT EXISTS daily_views (day TEXT PRIMARY KEY, views INTEGER NOT NULL DEFAULT 0) WITHOUT ROWID;
